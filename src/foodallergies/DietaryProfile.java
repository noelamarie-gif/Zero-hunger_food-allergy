    private void btnSaveDietaryProfileActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveDietaryProfileActionPerformed
        // TODO add your handling code here:

        String dietary = "";

// Collect selected dietary preferences
        if (chkVegan.isSelected()) {
            dietary += "Vegan, ";
        }

        if (chkVegetarian.isSelected()) {
            dietary += "Vegetarian, ";
        }

        if (chkDairyFree.isSelected()) {
            dietary += "Dairy-Free, ";
        }

        if (chkHalal.isSelected()) {
            dietary += "Halal, ";
        }

        if (chkGlutenFree.isSelected()) {
            dietary += "Gluten-Free, ";
        }

        if (chkOther.isSelected()) {
            dietary += "Other, ";
        }

// Get additional information
        String additionalInfo = txtDietaryInfo.getText();

        try {
            PrintWriter writer = new PrintWriter(
                    new FileWriter("dietary.txt", false)
            );

            writer.println("Dietary Preferences: " + dietary);
            writer.println("Additional Information: " + additionalInfo);
            writer.println("--------------------------------");

            writer.close();

            JOptionPane.showMessageDialog(this,
                    "Dietary Profile Saved Successfully!\n\n"
                    + "Dietary Preferences: " + dietary
                    + "\nAdditional Information: " + additionalInfo);

        } catch (IOException e) {
            JOptionPane.showMessageDialog(this,
                    "Error saving dietary profile: " + e.getMessage());
        }

    }//GEN-LAST:event_btnSaveDietaryProfileActionPerformed

